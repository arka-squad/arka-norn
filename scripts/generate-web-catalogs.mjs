import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { EN_MESSAGES } from "../dist/application/localization/messages/en.js";
import { FR_MESSAGES } from "../dist/application/localization/messages/fr.js";

const root = resolve(import.meta.dirname, "..");
const webRoot = resolve(root, "web");

const output = resolve(webRoot, "src", "generated");
mkdirSync(output, { recursive: true });
const webMessages = (catalog) => Object.fromEntries(Object.entries(catalog).filter(([key]) => key.startsWith("web.")));
const localeOutput = resolve(output, "locales");
mkdirSync(localeOutput, { recursive: true });
writeFileSync(resolve(localeOutput, "en.ts"), `// Generated by scripts/generate-web-catalogs.mjs. Do not edit.\nexport const enCatalog = ${JSON.stringify(webMessages(EN_MESSAGES), null, 2)} as const;\n`, "utf8");
writeFileSync(resolve(localeOutput, "fr.ts"), `// Generated by scripts/generate-web-catalogs.mjs. Do not edit.\nexport const frCatalog = ${JSON.stringify(webMessages(FR_MESSAGES), null, 2)} as const;\n`, "utf8");
writeFileSync(resolve(output, "catalogs.ts"), `// Generated by scripts/generate-web-catalogs.mjs. Do not edit.\nimport { enCatalog } from "./locales/en";\nimport { frCatalog } from "./locales/fr";\n\nexport const catalogs = { en: enCatalog, fr: frCatalog } as const;\n`, "utf8");

const pipelineCatalog = JSON.parse(readFileSync(resolve(root, "pipelines", "catalog.json"), "utf8"));
const packageManifest = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8"));
const contracts = {
  schemaVersion: 2,
  appVersion: packageManifest.version,
  defaultPipelineId: pipelineCatalog.defaultPipelineId,
  pipelines: pipelineCatalog.pipelines.map(({ id, aliases, name, description }) => ({ id, aliases, name, description })),
  documentContractVersion: 5,
  locales: ["en", "fr"],
};
writeFileSync(resolve(output, "contracts.ts"), `// Generated by scripts/generate-web-catalogs.mjs. Do not edit.\nexport const contracts = ${JSON.stringify(contracts, null, 2)} as const;\n`, "utf8");
